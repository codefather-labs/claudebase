//! HTTP callback API — external systems write into a session's input.
//!
//! `POST http://<bind>/callback/<nick>?label=<label>` with `X-Api-Token`, and the
//! body lands in that session's terminal input as `[callback:<label>]: <text>`.
//!
//! Nothing here invents a delivery mechanism: the request is authenticated,
//! resolved to a live agent, and handed to the same `send_message` + bus publish
//! path that peer messages use, so the injection gate (no modal, no half-typed
//! operator line) and the "queue rather than drop" guarantee come for free.
//!
//! Design notes live in `docs/plans/claudebase-v0.11-callback-api.md`. The two
//! that shape this file:
//!
//! * **A token belongs to a NICK, not to an `agent_id`.** Every restart mints a
//!   new `agent_id`, so a token keyed by it would change under every script that
//!   embeds it. The nick survives restarts, and it is also what the URL carries.
//! * **The listener is off until the operator turns it on.** Tokens exist from
//!   the first registration; an open port is a separate, deliberate act.

use std::net::SocketAddr;
use anyhow::{Context, Result};
use rusqlite::{params, Connection, OptionalExtension};
use sha2::{Digest, Sha256};

use super::chat::SharedBus;

/// `daemon_state` key holding the bind address, so an enabled listener survives
/// a daemon restart without the operator re-enabling it.
const BIND_KEY: &str = "callback.bind";

/// Where the operator (and their scripts) can read a token without going
/// through an agent.
fn token_dir() -> std::path::PathBuf {
    let home = std::env::var_os("HOME")
        .or_else(|| std::env::var_os("USERPROFILE"))
        .unwrap_or_else(|| std::ffi::OsString::from("/tmp"));
    std::path::PathBuf::from(home)
        .join(".claude")
        .join("callback-tokens")
}

