pub fn configured_bind(conn: &Connection) -> Result<Option<String>> {
    conn.query_row(
        "SELECT value FROM daemon_state WHERE key = ?1",
        params![BIND_KEY],
        |row| row.get::<_, String>(0),
    )
    .optional()
    .context("callback: read bind")
}

pub fn set_bind(conn: &Connection, bind: &str) -> Result<()> {
    conn.execute(
        "INSERT INTO daemon_state (key, value) VALUES (?1, ?2) \
         ON CONFLICT(key) DO UPDATE SET value = excluded.value",
        params![BIND_KEY, bind],
    )
    .context("callback: store bind")?;
    Ok(())
}

pub fn clear_bind(conn: &Connection) -> Result<()> {
    conn.execute(
        "DELETE FROM daemon_state WHERE key = ?1",
        params![BIND_KEY],
    )
    .context("callback: clear bind")?;
    Ok(())
}

