/// What a parsed request asked for, before any of it is trusted.
#[derive(Debug, PartialEq, Eq)]
pub struct CallbackRequest {
    pub target: String,
    pub label: Option<String>,
    pub token: Option<String>,
}

/// Keep a label to one token so it cannot forge a second prefix.
///
/// The label is pasted into the operator's input inside `[callback:<label>]`, so
/// a label of `x]: [telegram_message` would let a caller impersonate the
/// operator's own channel. Same rule and same reason as `sanitize_nick` in the
/// injector — which is why that function is reused rather than reimplemented.
pub fn sanitize_label(raw: &str) -> Option<String> {
    let cleaned = crate::supervisor::inject::sanitize_nick(raw);
    if cleaned == "unknown" && raw.chars().all(|c| !c.is_alphanumeric()) {
        return None;
    }
    Some(cleaned)
}

/// Percent-decoding for the query string. No dependency needed for the two
/// escapes that actually turn up in a label.
fn percent_decode(s: &str) -> String {
    let bytes = s.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        match bytes[i] {
            b'%' if i + 2 < bytes.len() => {
                let hi = (bytes[i + 1] as char).to_digit(16);
                let lo = (bytes[i + 2] as char).to_digit(16);
                match (hi, lo) {
                    (Some(h), Some(l)) => {
                        out.push((h * 16 + l) as u8);
                        i += 3;
                    }
                    _ => {
                        out.push(bytes[i]);
                        i += 1;
                    }
                }
            }
            b'+' => {
                out.push(b' ');
                i += 1;
            }
            b => {
                out.push(b);
                i += 1;
            }
        }
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// Pull the target and label out of a request-target like
/// `/callback/mira?label=ci`.
pub fn parse_target(path_and_query: &str) -> Option<(String, Option<String>)> {
    let (path, query) = match path_and_query.split_once('?') {
        Some((p, q)) => (p, Some(q)),
        None => (path_and_query, None),
    };
    let target = path.strip_prefix("/callback/")?.trim_matches('/');
    if target.is_empty() || target.contains('/') {
        return None;
    }
    let label = query.and_then(|q| {
        q.split('&')
            .find_map(|kv| kv.strip_prefix("label="))
            .map(percent_decode)
            .filter(|s| !s.is_empty())
            .and_then(|s| sanitize_label(&s))
    });
    Some((percent_decode(target), label))
}

/// Strip anything that would steer the operator's terminal rather than talk to
/// the agent.
///
/// The body is pasted into a pty. An ESC sequence in it is an attempt to drive
/// the terminal past the model — the one check that is NOT deferred in v1,
/// because it costs three lines and the body reaches the terminal directly.
pub fn sanitize_body(raw: &str) -> String {
    raw.chars()
        .filter(|c| *c == '\n' || *c == '\t' || !c.is_control())
        .collect()
}

/// The outcome of a callback, as the caller sees it.
///
/// The HTTP status is always 200 (operator decision): the caller is a debugging
/// script, not a client that needs to branch on status classes. The body still
/// says what happened, because in a debugging workflow a typo'd nick answering
/// exactly like a success is time spent chasing a delivery that never started.
#[derive(Debug)]
pub enum Outcome {
    Queued { message_id: String, target: String, subscribers: usize },
    Rejected { error: String, candidates: Vec<String> },
}

impl Outcome {
    pub fn to_json(&self) -> serde_json::Value {
        match self {
            Outcome::Queued { message_id, target, subscribers } => serde_json::json!({
                "ok": true,
                "delivery": if *subscribers > 0 { "delivered" } else { "queued" },
                "message_id": message_id,
                "target": target,
            }),
            Outcome::Rejected { error, candidates } => serde_json::json!({
                "ok": false,
                "error": error,
                "candidates": candidates,
            }),
        }
    }
}

/// Authenticate, resolve, and hand the message to the normal delivery path.
pub async fn dispatch(req: CallbackRequest, body: String, bus: &SharedBus) -> Outcome {
    let CallbackRequest { target, label, token } = req;
    let body = sanitize_body(&body);
    if body.trim().is_empty() {
        return Outcome::Rejected {
            error: "empty body".to_string(),
            candidates: vec![],
        };
    }

    let target_for_blocking = target.clone();
    let token_presented = token.unwrap_or_default();
    let resolved = tokio::task::spawn_blocking(move || -> anyhow::Result<(String, String)> {
        let conn = super::chat::open_chat_db()?;
        let agent_id = super::agent_registry::resolve_target(&conn, &target_for_blocking)?;
        // The token is checked against the NICK the URL names, so a token
        // cannot open a session other than its own.
        let nick: String = conn.query_row(
            "SELECT agent_name FROM agent_registry WHERE agent_id = ?1",
            params![agent_id],
            |row| row.get(0),
        )?;
        let expected = token_for(&conn, &nick)?
            .ok_or_else(|| anyhow::anyhow!("no callback token issued for `{nick}`"))?;
        if !tokens_match(&expected, &token_presented) {
            anyhow::bail!("unauthorized");
        }
        Ok((agent_id, nick))
    })
    .await;

    let (agent_id, nick) = match resolved {
        Ok(Ok(v)) => v,
        Ok(Err(e)) => {
            return Outcome::Rejected {
                error: e.to_string(),
                candidates: vec![],
            }
        }
        Err(e) => {
            tracing::error!(error = %e, "callback resolve panicked");
            return Outcome::Rejected {
                error: "internal error".to_string(),
                candidates: vec![],
            };
        }
    };

    deliver_resolved(&agent_id, &nick, &body, label.as_deref(), bus).await
}

/// Deliver a message that has already been authorised, to an agent named by
/// NICK, with no token involved.
///
/// This is the whole of what the UNIX-socket surface needs: a socket under the
/// user's own runtime directory is guarded by file permissions, so there is
/// nothing left for a token to prove. Sharing the code with the HTTP path is
/// the point — one delivery path means the injection gate, the storage and the
/// notification shape cannot drift apart between the two entry points.
pub async fn deliver(
    nick: &str,
    text: &str,
    label: Option<&str>,
    bus: &SharedBus,
) -> Outcome {
    let nick_owned = nick.to_string();
    let resolved = tokio::task::spawn_blocking(move || -> anyhow::Result<String> {
        let conn = super::chat::open_chat_db_readonly()?;
        super::agent_registry::resolve_target(&conn, &nick_owned)
    })
    .await;

    let agent_id = match resolved {
        Ok(Ok(id)) => id,
        Ok(Err(e)) => {
            return Outcome::Rejected {
                error: e.to_string(),
                candidates: vec![],
            }
        }
        Err(e) => {
            tracing::error!(error = %e, "socket deliver resolve panicked");
            return Outcome::Rejected {
                error: "internal error".to_string(),
                candidates: vec![],
            };
        }
    };

    deliver_resolved(&agent_id, nick, text, label, bus).await
}

async fn deliver_resolved(
    agent_id: &str,
    nick: &str,
    body: &str,
    label: Option<&str>,
    bus: &SharedBus,
) -> Outcome {
    let from = match label {
        Some(l) => format!("callback:{l}"),
        None => "callback".to_string(),
    };
    let content = body.to_string();
    let agent_for_send = agent_id.to_string();
    let from_for_send = from.clone();
    let stored = tokio::task::spawn_blocking(move || -> anyhow::Result<String> {
        let conn = super::chat::open_chat_db()?;
        let outcome = super::agent_registry::send_message(
            &conn,
            &from_for_send,
            &agent_for_send,
            &content,
            super::chat::now_millis(),
        )?;
        Ok(outcome.message_id)
    })
    .await;

    let message_id = match stored {
        Ok(Ok(id)) => id,
        Ok(Err(e)) => {
            return Outcome::Rejected {
                error: e.to_string(),
                candidates: vec![],
            }
        }
        Err(e) => {
            tracing::error!(error = %e, "callback store panicked");
            return Outcome::Rejected {
                error: "internal error".to_string(),
                candidates: vec![],
            };
        }
    };

    let thread = format!("agent:{agent_id}");
    let frame = super::chat::build_channel_notification_callback(
        body,
        label,
        agent_id,
        &message_id,
    );
    let subscribers = bus.publish(&thread, frame).await;

    tracing::info!(
        target_nick = %nick,
        label = ?label,
        %message_id,
        subscribers,
        "callback accepted"
    );

    Outcome::Queued {
        message_id,
        target: nick.to_string(),
        subscribers,
    }
}

