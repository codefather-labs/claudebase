/// Keyed by nick alone, matching the URL: `/callback/<nick>`.
///
/// Not by (nick, cwd) — a nick identifies at most one live session, so the URL
/// could not disambiguate two rows anyway, and a lookup that can return two
/// answers for one address is a lookup that will eventually return the wrong one.
pub fn apply_migration(conn: &Connection) -> rusqlite::Result<()> {
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS callback_tokens (
           nick       TEXT PRIMARY KEY,
           token      TEXT NOT NULL,
           label      TEXT,
           created_at INTEGER NOT NULL
         );",
    )
}

/// 32 bytes from the OS CSPRNG, hex-encoded.
///
/// Deliberately not generated by the model that hands it to the operator: LLM
/// output is not a random source, it is a biased and partly predictable one.
fn mint() -> Result<String> {
    let mut raw = [0u8; 32];
    getrandom::getrandom(&mut raw).context("callback: read CSPRNG")?;
    Ok(hex::encode(raw))
}

/// First 8 hex characters of the token's SHA-256.
///
/// Safe to print anywhere the token is not: it identifies which token is in
/// force (so a script's copy can be compared against the daemon's) without
/// being usable as one.
pub fn fingerprint(token: &str) -> String {
    let digest = Sha256::digest(token.as_bytes());
    hex::encode(digest)[..8].to_string()
}

/// The token for `nick`, creating one on first use.
///
/// Called at agent registration so a session always has a token without the
/// operator asking for it.
pub fn ensure_token(conn: &Connection, nick: &str, now_ms: i64) -> Result<String> {
    if let Some(existing) = token_for(conn, nick)? {
        return Ok(existing);
    }
    let token = mint()?;
    conn.execute(
        "INSERT OR IGNORE INTO callback_tokens (nick, token, created_at) VALUES (?1, ?2, ?3)",
        params![nick, token, now_ms],
    )
    .context("callback: store token")?;
    // A concurrent registration may have won the race; read back rather than
    // returning a token that is not the one in force.
    let stored = token_for(conn, nick)?.unwrap_or(token);
    write_token_file(nick, &stored);
    Ok(stored)
}

pub fn token_for(conn: &Connection, nick: &str) -> Result<Option<String>> {
    conn.query_row(
        "SELECT token FROM callback_tokens WHERE nick = ?1",
        params![nick],
        |row| row.get::<_, String>(0),
    )
    .optional()
    .context("callback: read token")
}

/// New token, old one dead immediately.
pub fn rotate(conn: &Connection, nick: &str, now_ms: i64) -> Result<String> {
    let token = mint()?;
    conn.execute(
        "INSERT INTO callback_tokens (nick, token, created_at) VALUES (?1, ?2, ?3) \
         ON CONFLICT(nick) DO UPDATE SET token = excluded.token, created_at = excluded.created_at",
        params![nick, token, now_ms],
    )
    .context("callback: rotate token")?;
    write_token_file(nick, &token);
    Ok(token)
}

/// Follow a rename, exactly as chat bindings do.
///
/// The token addresses the session, and the session's address just changed. A
/// token left on the abandoned nick would authenticate nobody while the scripts
/// holding it silently stopped working.
pub fn rename(conn: &Connection, old_nick: &str, new_nick: &str) -> Result<usize> {
    let moved = conn
        .execute(
            "UPDATE OR REPLACE callback_tokens SET nick = ?2 WHERE nick = ?1",
            params![old_nick, new_nick],
        )
        .context("callback: move token to new nick")?;
    if moved > 0 {
        if let Ok(Some(tok)) = token_for(conn, new_nick) {
            write_token_file(new_nick, &tok);
        }
        let _ = std::fs::remove_file(token_dir().join(old_nick));
    }
    Ok(moved)
}

/// Mirror the token into `~/.claude/callback-tokens/<nick>` (0600).
///
/// So a local script can read the secret instead of embedding it: the literal
/// then never enters the script, the shell history, or git.
fn write_token_file(nick: &str, token: &str) {
    // A nick is validated on the way into the registry, but this builds a PATH
    // — a traversal here would write outside the directory.
    if nick.is_empty() || nick.contains('/') || nick.contains('\\') || nick.contains("..") {
        tracing::warn!(nick, "refusing to write a token file for a path-unsafe nick");
        return;
    }
    let dir = token_dir();
    if let Err(e) = std::fs::create_dir_all(&dir) {
        tracing::warn!(error = %e, "callback: cannot create token dir");
        return;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o700));
    }
    let path = dir.join(nick);
    if let Err(e) = std::fs::write(&path, token) {
        tracing::warn!(error = %e, "callback: cannot write token file");
        return;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o600));
    }
}

/// Constant-time comparison — a byte-by-byte `==` leaks the token through
/// response timing, one character at a time.
fn tokens_match(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for (x, y) in a.iter().zip(b.iter()) {
        diff |= x ^ y;
    }
    diff == 0
}

